#!/usr/bin/env node
/**
 * Execution evidence for the submission (PRD Sections 12 and 13).
 *
 *   npm run evidence
 *
 * Runs the acceptance scripts (S1 to S8, I1 to I3, ST1 to ST8) and the recorded
 * run, then writes into evidence/:
 *
 *   results.md             one row per script, with pass or fail
 *   audit-log.json         the audit log exported from the recorded run
 *   chat-transcript.json   what was asked and what the agent answered
 *   outbound-requests.json every request the privacy panel recorded
 *
 * The audit log is then checked with the same verifier as `npm run verify:audit`.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const root = process.cwd();
const directory = join(root, 'evidence');
mkdirSync(directory, { recursive: true });

// The raw report holds absolute paths from this machine, so it stays out of evidence/.
const scratch = mkdtempSync(join(tmpdir(), 'evidence-'));
const report = join(scratch, 'test-results.json');
const run = spawnSync(
  process.execPath,
  [
    join(root, 'node_modules', 'vitest', 'vitest.mjs'),
    'run',
    'src/acceptance',
    '--reporter=json',
    `--outputFile=${report}`,
  ],
  { cwd: root, env: { ...process.env, EVIDENCE: '1' }, stdio: 'inherit' },
);

const results = JSON.parse(readFileSync(report, 'utf8'));
rmSync(scratch, { recursive: true, force: true });
const rows = [];
for (const file of results.testResults ?? []) {
  for (const test of file.assertionResults ?? []) {
    const id = /^(S\d|I\d|ST\d|CHAT-\d|POL-\d)/.exec(test.title)?.[1] ?? '';
    rows.push({
      id,
      group: (test.ancestorTitles ?? []).join(' / '),
      title: test.title,
      status: test.status,
    });
  }
}

const order = (id) => {
  const match = /^([A-Z-]+)(\d+)$/.exec(id);
  const rank = { S: 0, I: 1, ST: 2 }[match?.[1] ?? ''] ?? 3;
  return rank * 100 + Number(match?.[2] ?? 99);
};
rows.sort((a, b) => order(a.id) - order(b.id));

const passed = rows.filter((row) => row.status === 'passed').length;
const cell = (text) => String(text).replace(/\|/g, '\\|');
const lines = [
  '# Acceptance results',
  '',
  `Generated by \`npm run evidence\` on ${new Date().toISOString().slice(0, 10)}, against the rule-based model.`,
  '',
  `**${passed} of ${rows.length} checks passed.**`,
  '',
  '| ID | Check | Result |',
  '| --- | --- | --- |',
  ...rows.map(
    (row) => `| ${row.id || '-'} | ${cell(row.title)} | ${row.status === 'passed' ? 'pass' : 'FAIL'} |`,
  ),
  '',
  'I4 (golden path in 6 user actions or fewer) is checked in a real browser by `npm run e2e`',
  '(`tests/e2e/golden-path.spec.ts`).',
  '',
];
writeFileSync(join(directory, 'results.md'), lines.join('\n'));
console.log(`wrote evidence/results.md (${passed} of ${rows.length} passed)`);

const verify = spawnSync(
  process.execPath,
  [
    '--experimental-strip-types',
    join(root, 'src', 'audit', 'verify-cli.ts'),
    join(directory, 'audit-log.json'),
  ],
  { cwd: root, stdio: 'inherit' },
);

process.exit(run.status === 0 && verify.status === 0 && passed === rows.length ? 0 : 1);
